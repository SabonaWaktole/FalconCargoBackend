CREATE TABLE contact_us_model
(
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    sender_email VARCHAR(255)                             NOT NULL,
    sender_name  VARCHAR(255)                             NOT NULL,
    message      VARCHAR(255)                             NOT NULL,
    subject      VARCHAR(255),
    CONSTRAINT pk_contactusmodel PRIMARY KEY (id)
);

CREATE TABLE good_model
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name           VARCHAR(255)                             NOT NULL,
    width          DOUBLE PRECISION                         NOT NULL,
    height         DOUBLE PRECISION                         NOT NULL,
    length         DOUBLE PRECISION                         NOT NULL,
    weight         DOUBLE PRECISION                         NOT NULL,
    nature         VARCHAR(255)                             NOT NULL,
    state          SMALLINT                                 NOT NULL,
    pieces         INTEGER                                  NOT NULL,
    density        DOUBLE PRECISION                         NOT NULL,
    volume         DOUBLE PRECISION                         NOT NULL,
    sender_email   VARCHAR(255)                             NOT NULL,
    receiver_email VARCHAR(255)                             NOT NULL,
    CONSTRAINT pk_goodmodel PRIMARY KEY (id)
);

CREATE TABLE person_model
(
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email             VARCHAR(255)                             NOT NULL,
    first_name        VARCHAR(255)                             NOT NULL,
    middle_name       VARCHAR(255),
    last_name         VARCHAR(255)                             NOT NULL,
    primary_address   VARCHAR(255)                             NOT NULL,
    city              VARCHAR(255)                             NOT NULL,
    state             VARCHAR(255)                             NOT NULL,
    country           VARCHAR(255)                             NOT NULL,
    phone_number      VARCHAR(255)                             NOT NULL,
    fax_number        VARCHAR(255),
    zip_code          VARCHAR(255),
    secondary_address VARCHAR(255),
    languages         TEXT[],
    vat               VARCHAR(255),
    service_count     INTEGER,
    CONSTRAINT pk_personmodel PRIMARY KEY (id)
);

